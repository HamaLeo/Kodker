  /**
   * پشکنینی وەڵامی بەکارهێنەر.
   * @param lesson وانەکە
   * @param lines  ڕیزەکانی دەرچوون
   * @param source کۆدی نووسراو
   * @param Kodker کتێبخانەی کۆدکەر (بۆ دۆزینەوەی وشەکان)
   * @param gfx    وێنەی کێشراو (ئەگەر هەبێت)
   * @returns {{ok:boolean, reason?:string, expected?:string[], got?:string[]}}
   */
  function check(lesson, lines, source, Kodker, gfx) {
    const words = new Set(Kodker.tokenize(source).filter((t) => t.type === 'word').map((t) => t.text));
    for (const w of lesson.mustUse || []) {
      if (!words.has(w)) return { ok: false, reason: `لە کۆدەکەتدا دەبێت «${w}» بەکاربهێنیت.` };
    }
    // پشکنینی وێنە: ژمارەی کەمترینی هەر جۆرە شێوەیەک و ژمارەی فریم
    if (lesson.expectDraw || lesson.expectAny || lesson.minFrames) {
      const cmds = gfx ? gfx.frames.flat() : [];
      for (const [op, min] of Object.entries(lesson.expectDraw || {})) {
        const n = cmds.filter((c) => c[0] === op).length;
        if (n < min) {
          return { ok: false, reason: `پێویستە لانیکەم ${min} «${DRAW_NAMES[op] || op}» بکێشرێت، بەڵام ${n} کێشرا.` };
        }
      }
      if (lesson.expectAny && !cmds.some((c) => lesson.expectAny.includes(c[0]))) {
        const names = lesson.expectAny.map((o) => DRAW_NAMES[o] || o).join(' / ');
        return { ok: false, reason: `نیشانەیەک لە ناوەڕاستدا دابنێ: ${names}.` };
      }
      if (lesson.minFrames && (!gfx || gfx.frames.length < lesson.minFrames)) {
        return { ok: false, reason: `پێویستە لانیکەم ${lesson.minFrames} فریم هەبێت (بە «فریم()»)، بەڵام ${gfx ? gfx.frames.length : 0} هەیە.` };
      }
    }
    if (!lesson.expect) return { ok: true };
    const got = lines.map((l) => String(l).trim());
    const expected = lesson.expect;
    for (let i = 0; i < Math.max(got.length, expected.length); i++) {
      if (got[i] !== expected[i]) {
        const reason = i >= got.length
          ? 'دەرچوونەکەت کورتە. هێشتا ڕیزی ' + (i + 1) + ' کەمە.'
          : i >= expected.length
            ? 'دەرچوونەکەت زیاتر ڕیزی هەیە لە پێویست.'
            : 'ڕیزی ' + (i + 1) + ' جیاوازە.';
        return { ok: false, reason, expected, got };
      }
    }
    return { ok: true };
  }

  /** پێشکەوتنی کۆن (ژمارەی وانە، ٠-بنەما) دەگۆڕێت بۆ id */
  function legacyToIds(indices) {
    return (indices || []).map((i) => LEGACY_ORDER[i]).filter(Boolean);
  }

  return { chapters, lessons, check, legacyToIds, LEGACY_ORDER, LEVELS };
