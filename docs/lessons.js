  /** وانە نوێیەکان دەخاتە شوێنی خۆیان لە ڕیزبەندیی بەشەکاندا */
  function compose(base, extra) {
    const out = [];
    for (const l of base) {
      out.push(l);
      for (const e of extra) if (e.after === l.id) out.push(e);
    }
    return out;
  }

